create table if not exists public.altea_boards (id text primary key, title text not null, access_hash text not null);
create table if not exists public.altea_tasks (
 id bigint generated by default as identity primary key,
 board_id text not null references public.altea_boards(id) on delete cascade,
 code text not null, category text not null, title text not null,
 description text not null, hours numeric(5,1) not null default 0,
 modules text[] not null default '{}',
 status text not null default 'todo' check(status in ('todo','doing','testing','done')),
 owner text not null default '', priority text not null default 'normal' check(priority in ('low','normal','high')),
 notes text not null default '', updated_by text not null default '',
 updated_at timestamptz, unique(board_id,code)
);
alter table public.altea_boards enable row level security;
alter table public.altea_tasks enable row level security;
revoke all on public.altea_boards from public, anon, authenticated;
revoke all on public.altea_tasks from public, anon, authenticated;
create or replace function public.altea_get_tasks(p_board_id text,p_key text)
returns jsonb language plpgsql security definer set search_path='' as $$
begin
 if not exists(select 1 from public.altea_boards b where b.id=p_board_id and b.access_hash=pg_catalog.encode(pg_catalog.sha256(pg_catalog.convert_to(p_key,'UTF8')),'hex')) then
   raise exception 'Clave de tablero incorrecta' using errcode='42501';
 end if;
 return pg_catalog.jsonb_build_object('board_id',p_board_id,'tasks',coalesce(
   (select pg_catalog.jsonb_agg(pg_catalog.to_jsonb(t) order by t.code) from public.altea_tasks t where t.board_id=p_board_id),'[]'::jsonb));
end; $$;
create or replace function public.altea_update_task(
 p_board_id text,p_key text,p_code text,p_status text,p_owner text,p_priority text,p_notes text,p_actor text
) returns jsonb language plpgsql security definer set search_path='' as $$
declare t_result jsonb;
begin
 if not exists(select 1 from public.altea_boards b where b.id=p_board_id and b.access_hash=pg_catalog.encode(pg_catalog.sha256(pg_catalog.convert_to(p_key,'UTF8')),'hex')) then
   raise exception 'Clave de tablero incorrecta' using errcode='42501';
 end if;
 if p_status not in ('todo','doing','testing','done') or p_priority not in ('low','normal','high') then raise exception 'Estado o prioridad incorrectos'; end if;
 if pg_catalog.char_length(coalesce(p_owner,''))>60 or pg_catalog.char_length(coalesce(p_actor,''))>60 or pg_catalog.char_length(coalesce(p_notes,''))>2500 then raise exception 'Campo demasiado largo'; end if;
 update public.altea_tasks t set status=p_status, owner=coalesce(p_owner,''), priority=p_priority,
 notes=coalesce(p_notes,''),updated_by=coalesce(p_actor,''),updated_at=now()
 where t.board_id=p_board_id and t.code=p_code returning pg_catalog.to_jsonb(t) into t_result;
 if t_result is null then raise exception 'Tarea no encontrada'; end if;
 return t_result;
end; $$;
